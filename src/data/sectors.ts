/** Strategic-layer biome. Drives the tactical map generator's tileset and prop tables. */
export type SectorBiome =
  | 'village'
  | 'farmland'
  | 'woods'
  | 'industrial'
  | 'highway'
  | 'ruins'
  | 'military'
  | 'swamp';

export interface SectorDef {
  /** Column letter + row number, e.g. 'c4'. */
  id: string;
  x: number;
  y: number;
  name: string;
  terrain: SectorBiome;
  /** Faction id, or null for contested/empty ground. */
  owner: string | null;
  /** 1 (quiet) .. 5 (do not go in without a plan). */
  threat: number;
  /** Relative abundance weights for a scavenging run here. Absent = not found. */
  scavengeTable: Materials;
  /** One line, shown on map hover. */
  blurb: string;
  landmark?: string;
}

