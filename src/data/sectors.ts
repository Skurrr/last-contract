/**
 * The Basin — an 8x6 sector grid around a drained reservoir.
 *
 * Geography is the story here:
 *   - Havenhold farms the south-west bottomland, walled, and feeds the valley.
 *   - The Rust Kings hold the interstate: column E top to bottom, a spine that physically
 *     separates Havenhold from everyone east of it.
 *   - The Ash Order squats in the reservoir ruins in the middle-north-west, on the dam and
 *     in the town the water used to cover.
 *   - The Remnant hold Fort Aldrich in the far north-east and almost never leave it.
 *   - Free Traders own no ground worth fighting for — a junction and a truck stop, both
 *     deliberately on other people's borders.
 *
 * Sector ids are column letter + 1-based row: 'a1' is north-west, 'h6' is south-east.
 * Faction ids referenced in `owner` come from src/data/factions.ts.
 */
